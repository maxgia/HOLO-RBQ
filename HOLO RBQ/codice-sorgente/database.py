import json
import os
from pathlib import Path

from sqlalchemy import create_engine, inspect, text
from sqlalchemy.engine import make_url

ROOT = Path(__file__).resolve().parent
CONFIG = ROOT / 'data' / 'postgres.json'
WRITE_LOCK = 470091
TABLE_COLUMNS = {
    'clients': ['id', 'name', 'email', 'phone'],
    'previews': ['id', 'client', 'subject', 'amount', 'discount', 'total', 'client_id'],
    'drafts': ['id', 'preview_id', 'client', 'subject', 'amount', 'discount', 'total', 'client_id', 'version'],
    'invoices': ['number', 'client_id', 'due_date', 'amount', 'paid'],
    'demo_payments': ['request_id', 'invoice_number', 'amount'],
    'follow_ups': ['id', 'client_id', 'title', 'due_date', 'completed', 'invoice_number', 'draft_id'],
    'edits': ['preview_id', 'draft_id', 'base_version', 'confirmed'],
    'follow_up_emails': ['follow_up_id', 'recipient', 'subject', 'body', 'send_at', 'expected_remaining', 'status', 'detail', 'sent_at'],
}
ORDER = ['clients', 'previews', 'drafts', 'invoices', 'demo_payments', 'follow_ups', 'edits', 'follow_up_emails']
DDL = """
CREATE TABLE IF NOT EXISTS clients (id TEXT PRIMARY KEY, name TEXT NOT NULL, email TEXT NOT NULL DEFAULT '', phone TEXT NOT NULL DEFAULT '');
CREATE TABLE IF NOT EXISTS previews (id TEXT PRIMARY KEY, client TEXT NOT NULL, subject TEXT NOT NULL, amount BIGINT NOT NULL, discount BIGINT NOT NULL, total BIGINT NOT NULL, client_id TEXT REFERENCES clients(id));
CREATE TABLE IF NOT EXISTS drafts (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, preview_id TEXT NOT NULL UNIQUE, client TEXT NOT NULL, subject TEXT NOT NULL, amount BIGINT NOT NULL, discount BIGINT NOT NULL, total BIGINT NOT NULL, client_id TEXT REFERENCES clients(id), version TEXT NOT NULL DEFAULT '');
CREATE TABLE IF NOT EXISTS invoices (number TEXT PRIMARY KEY, client_id TEXT NOT NULL REFERENCES clients(id), due_date TEXT NOT NULL, amount BIGINT NOT NULL, paid BIGINT NOT NULL);
CREATE TABLE IF NOT EXISTS demo_payments (request_id TEXT PRIMARY KEY, invoice_number TEXT NOT NULL REFERENCES invoices(number), amount BIGINT NOT NULL CHECK(amount > 0));
CREATE TABLE IF NOT EXISTS follow_ups (id TEXT PRIMARY KEY, client_id TEXT NOT NULL REFERENCES clients(id), title TEXT NOT NULL, due_date TEXT NOT NULL, completed INTEGER NOT NULL DEFAULT 0, invoice_number TEXT REFERENCES invoices(number), draft_id TEXT, CHECK(invoice_number IS NULL OR draft_id IS NULL));
CREATE TABLE IF NOT EXISTS edits (preview_id TEXT PRIMARY KEY, draft_id BIGINT NOT NULL REFERENCES drafts(id), base_version TEXT NOT NULL, confirmed INTEGER NOT NULL DEFAULT 0);
CREATE TABLE IF NOT EXISTS follow_up_emails (follow_up_id TEXT PRIMARY KEY REFERENCES follow_ups(id), recipient TEXT NOT NULL, subject TEXT NOT NULL, body TEXT NOT NULL, send_at TEXT NOT NULL, expected_remaining BIGINT, status TEXT NOT NULL DEFAULT 'scheduled', detail TEXT NOT NULL DEFAULT '', sent_at TEXT);
CREATE TABLE IF NOT EXISTS _holo_migrations (source_digest TEXT PRIMARY KEY, schema_version INTEGER NOT NULL, report_json TEXT NOT NULL);
"""


def postgres_url(value=None, config=CONFIG):
    value = value or os.getenv('HOLO_DATABASE_URL')
    if not value and config.is_file():
        value = json.loads(config.read_text(encoding='utf-8'))['url']
    if not value:
        raise ValueError('PostgreSQL non configurato. Esegui prima migrate_to_postgres.py --configure con il tuo archivio SQLite.')
    url = make_url(value)
    if url.get_backend_name() != 'postgresql':
        raise ValueError('L’app richiede PostgreSQL; non viene usato un archivio SQLite di ripiego.')
    return url.set(drivername='postgresql+psycopg')


def engine_for(value):
    return create_engine(postgres_url(value), pool_pre_ping=True, hide_parameters=True,
                         connect_args={'connect_timeout': 5})


def create_schema(connection):
    connection.execute(text('SELECT pg_advisory_xact_lock(:key)'), {'key': WRITE_LOCK})
    for statement in DDL.split(';'):
        if statement.strip():
            connection.execute(text(statement))
    for table, expected in TABLE_COLUMNS.items():
        actual = {item['name'] for item in inspect(connection).get_columns(table)}
        if actual != set(expected):
            raise ValueError('Schema PostgreSQL non compatibile: ' + table)


class Row(dict):
    def __getitem__(self, key):
        return list(self.values())[key] if isinstance(key, int) else super().__getitem__(key)


class Result:
    def __init__(self, result):
        self.result = result
        self.rowcount = result.rowcount

    def fetchone(self):
        row = self.result.fetchone()
        return Row(row._mapping) if row is not None else None

    def fetchall(self):
        return [Row(row._mapping) for row in self.result.fetchall()]

    def __iter__(self):
        return iter(self.fetchall())


class Connection:
    def __init__(self, engine):
        self.connection = engine.connect()
        self.locked = False

    def __enter__(self):
        return self

    def __exit__(self, error_type, error, tb):
        if error_type is None:
            self.connection.commit()
        else:
            self.connection.rollback()
        self.locked = False

    def close(self):
        self.connection.close()

    def lock(self):
        if not self.locked:
            self.connection.execute(text('SELECT pg_advisory_xact_lock(:key)'), {'key': WRITE_LOCK})
            self.locked = True

    def execute(self, statement, params=()):
        command = statement.strip().upper()
        if command == 'BEGIN IMMEDIATE':
            self.lock()
            return None
        if command == 'BEGIN':
            self.connection.execute(text('SET TRANSACTION ISOLATION LEVEL REPEATABLE READ'))
            return None
        if command == 'BEGIN READ ONLY':
            self.connection.execute(text('SET TRANSACTION ISOLATION LEVEL REPEATABLE READ, READ ONLY'))
            return None
        if command.startswith(('INSERT', 'UPDATE', 'DELETE')):
            self.lock()
        if isinstance(params, dict):
            bound = dict(params)
        else:
            parts = statement.split('?')
            if len(parts) != len(params) + 1:
                raise ValueError('Numero parametri SQL non coerente.')
            statement = parts[0] + ''.join(f':p{i}' + part for i, part in enumerate(parts[1:]))
            bound = {f'p{i}': value for i, value in enumerate(params)}
        bound = {key: int(value) if isinstance(value, bool) else value for key, value in bound.items()}
        return Result(self.connection.execute(text(statement), bound))


class PostgresStore:
    def __init__(self, value):
        self.engine = engine_for(value)
        with self.engine.connect() as connection:
            if not inspect(connection).has_table('_holo_migrations'):
                raise ValueError('Database PostgreSQL non migrato. Esegui migrate_to_postgres.py prima di avviare HOLO.')
            rows = connection.execute(text('SELECT schema_version FROM _holo_migrations')).all()
            if not rows or any(row[0] != 1 for row in rows):
                raise ValueError('Versione dello schema non riconosciuta o migrazione assente.')

    def connect(self):
        return Connection(self.engine)
